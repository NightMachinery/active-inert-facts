PROMPT_DIR = Path(__file__).resolve().parents[1] / "data" / "prompts"

PROMPT_FILES = ("frames.yaml", "few_shot.yaml", "sandbox.yaml", "wild.yaml")

@dataclass(frozen=True)
class Frame:
    name: str
    template: str
    why: str

@dataclass(frozen=True)
class TokenizerProbe:
    text: str
    continuation: str
    why: str

@dataclass(frozen=True)
class FewShotSpec:
    n_shots: int
    demonstration: str
    test_line: str
    separator: str
    support_rule: str

    def render(
        self,
        template: str,
        support: Sequence[tuple[str, str]],
        test_subject: str,
    ) -> str:
        lines = [
            self.demonstration.format(prompt=template.format(subject), object=obj)
            for subject, obj in support
        ]
        lines.append(self.test_line.format(prompt=template.format(test_subject)))
        return self.separator.join(lines)

@dataclass(frozen=True)
class Paraphrase:
    name: str
    template: str

@dataclass(frozen=True)
class TownRegionPrompts:
    relation_name: str
    relation_type: str
    domain_name: str
    range_name: str
    templates: tuple[str, ...]
    prompt_templates_zs: tuple[str, ...]
    subject_file: str
    subject_column: str
    object_file: str
    object_key_column: str
    object_value_column: str
    strip_leading: str

    def object_phrase(self, prompt_phrase: str) -> str:
        if self.strip_leading and prompt_phrase.startswith(self.strip_leading):
            return prompt_phrase[len(self.strip_leading) :]
        return prompt_phrase

@dataclass(frozen=True)
class SandboxPrompts:
    train: tuple[Paraphrase, ...]
    gate: tuple[Paraphrase, ...]
    target: str
    town_region: TownRegionPrompts

    def as_template_map(self) -> dict[str, dict[str, str]]:
        return {
            "train": {p.name: p.template for p in self.train},
            "gate": {p.name: p.template for p in self.gate},
        }

@dataclass(frozen=True)
class WildPrompts:
    name: str
    slug: str
    relation_type: str
    source_file: str
    source_sha256: str
    templates: tuple[str, ...]
    prompt_templates_zs: tuple[str, ...]

def check_template(template: str, where: str,
                   allow: Sequence[str] = ()) -> str:
    if not isinstance(template, str):
        raise ValueError(f"{where}: template is {type(template).__name__}, not str")
    if template.count("{}") != 1:
        raise ValueError(
            f"{where}: template {template!r} has {template.count('{}')} "
            f"'{{}}' placeholders, expected exactly 1"
        )
    bare = template.replace("{}", "")
    for slot in allow:
        bare = bare.replace(slot, "")
    if bare.count("{") or bare.count("}"):
        raise ValueError(f"{where}: template {template!r} has a stray brace")
    return template

def _unique_names(items: Sequence[Paraphrase] | Sequence[Frame], where: str) -> None:
    names = [i.name for i in items]
    if len(set(names)) != len(names):
        raise ValueError(f"{where}: duplicate names in {names}")

@lru_cache(maxsize=None)
def _document(filename: str) -> dict:
    path = PROMPT_DIR / filename
    if not path.exists():
        raise FileNotFoundError(
            f"{path} is missing.  Prompt files are part of the repository; "
            f"wild.yaml is regenerated by scripts/snapshot_wild_prompts.py."
        )
    return yaml.safe_load(path.read_text(encoding="utf-8"))

def clear_cache() -> None:
    _document.cache_clear()
    neutral_frames.cache_clear()
    tokenizer_probe.cache_clear()
    few_shot_spec.cache_clear()
    sandbox_prompts.cache_clear()
    _wild_index.cache_clear()

@lru_cache(maxsize=None)
def neutral_frames() -> tuple[Frame, ...]:
    doc = _document("frames.yaml")
    frames = tuple(
        Frame(
            name=f["name"],
            template=check_template(f["template"], f"frames.yaml:{f['name']}"),
            why=f["why"],
        )
        for f in doc["frames"]
    )
    _unique_names(frames, "frames.yaml")
    if not frames:
        raise ValueError("frames.yaml lists no frames")
    return frames

@lru_cache(maxsize=None)
def tokenizer_probe() -> TokenizerProbe:
    probe = _document("frames.yaml")["tokenizer_probe"]
    if not probe["text"].strip() or not probe["continuation"].strip():
        raise ValueError("frames.yaml:tokenizer_probe: text and continuation "
                         "must both hold visible characters")
    return TokenizerProbe(
        text=probe["text"],
        continuation=probe["continuation"],
        why=probe["why"],
    )

def neutral_templates() -> tuple[str, ...]:
    return tuple(f.template for f in neutral_frames())

@lru_cache(maxsize=None)
def few_shot_spec() -> FewShotSpec:
    doc = _document("few_shot.yaml")
    spec = FewShotSpec(
        n_shots=int(doc["n_shots"]),
        demonstration=doc["demonstration"],
        test_line=doc["test_line"],
        separator=doc["separator"],
        support_rule=doc["support_rule"],
    )
    if spec.n_shots < 1:
        raise ValueError(f"few_shot.yaml: n_shots={spec.n_shots}")
    for field, value in (("demonstration", spec.demonstration),
                         ("test_line", spec.test_line)):
        if "{prompt}" not in value:
            raise ValueError(f"few_shot.yaml:{field} does not use {{prompt}}")
    if "{object}" not in spec.demonstration:
        raise ValueError("few_shot.yaml:demonstration does not use {object}")
    if "{object}" in spec.test_line:
        raise ValueError(
            "few_shot.yaml:test_line uses {object}: the test line must not "
            "carry the answer it is asking for"
        )
    return spec

@lru_cache(maxsize=None)
def sandbox_prompts() -> SandboxPrompts:
    doc = _document("sandbox.yaml")
    animal, region = doc["town_animal"], doc["town_region"]

    def paraphrases(key: str) -> tuple[Paraphrase, ...]:
        return tuple(
            Paraphrase(
                name=p["name"],
                template=check_template(
                    p["template"], f"sandbox.yaml:town_animal.{key}.{p['name']}"
                ),
            )
            for p in animal[key]
        )

    train, gate = paraphrases("train"), paraphrases("gate")
    _unique_names(train + gate, "sandbox.yaml:town_animal")
    templates = tuple(
        check_template(t, f"sandbox.yaml:town_region.templates[{i}]")
        for i, t in enumerate(region["templates"])
    )
    zs = tuple(
        check_template(t, f"sandbox.yaml:town_region.prompt_templates_zs[{i}]")
        for i, t in enumerate(region["prompt_templates_zs"])
    )
    unknown = [t for t in zs if t not in templates]
    if unknown:
        raise ValueError(
            f"sandbox.yaml:town_region: zero-shot template {unknown[0]!r} is "
            f"not one of the relation's templates"
        )
    return SandboxPrompts(
        train=train,
        gate=gate,
        target=animal["target"],
        town_region=TownRegionPrompts(
            relation_name=region["relation_name"],
            relation_type=region["relation_type"],
            domain_name=region["domain_name"],
            range_name=region["range_name"],
            templates=templates,
            prompt_templates_zs=zs,
            subject_file=region["subjects"]["file"],
            subject_column=region["subjects"]["column"],
            object_file=region["objects"]["file"],
            object_key_column=region["objects"]["key_column"],
            object_value_column=region["objects"]["value_column"],
            strip_leading=region["objects"]["strip_leading"],
        ),
    )

@lru_cache(maxsize=None)
def _wild_index() -> dict[str, WildPrompts]:
    doc = _document("wild.yaml")
    out: dict[str, WildPrompts] = {}
    for entry in doc["relations"]:
        name = entry["name"]
        if name in out:
            raise ValueError(f"wild.yaml: duplicate relation name {name!r}")
        out[name] = WildPrompts(
            name=name,
            slug=entry["slug"],
            relation_type=entry["relation_type"],
            source_file=entry["source_file"],
            source_sha256=entry["source_sha256"],
            templates=tuple(
                check_template(t, f"wild.yaml:{name}.templates[{i}]")
                for i, t in enumerate(entry["templates"])
            ),
            prompt_templates_zs=tuple(
                check_template(t, f"wild.yaml:{name}.prompt_templates_zs[{i}]")
                for i, t in enumerate(entry["prompt_templates_zs"])
            ),
        )
    return out

def wild_prompts(name: str | None = None):
    index = _wild_index()
    if name is None:
        return index
    try:
        return index[name]
    except KeyError:
        raise KeyError(
            f"relation {name!r} is not in {PROMPT_DIR / 'wild.yaml'}.  "
            f"Regenerate it with scripts/snapshot_wild_prompts.py "
            f"--relations-dir <the checkout> and commit the result."
        ) from None

def wild_relation(name: str, source_path: Path | str) -> WildPrompts:
    entry = wild_prompts(name)
    path = Path(source_path)
    actual = sha256_file(path)
    if actual != entry.source_sha256:
        raise ValueError(
            f"{path} has changed since data/prompts/wild.yaml was written: "
            f"sha256 {actual} on disk, {entry.source_sha256} recorded for "
            f"relation {name!r}.  The prompts in wild.yaml may no longer be "
            f"the ones in that file.  Re-run scripts/snapshot_wild_prompts.py "
            f"and commit the result, or restore the original checkout."
        )
    return entry

def sha256_file(path: Path | str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()

def digests() -> dict[str, str]:
    out: dict[str, str] = {}
    for name in PROMPT_FILES:
        path = PROMPT_DIR / name
        out[name] = sha256_file(path) if path.exists() else None
    return out
